import {test} from "node:test";
import assert from "node:assert/strict";
import {requestHash} from "@worker-plane/protocol";
import {openDatabase} from "../src/storage.js";
import {ExecutionCoordinator} from "../src/execution.js";
import {MAX_FRAME_BYTES} from "@worker-plane/protocol";

test("P2 dispatch binds a persisted intent, commits a matching result, then ACKs it",async()=>{
 const db=openDatabase(":memory:");
 db.prepare("INSERT INTO workers VALUES('venus','boot','ledger',2,1,1,0,?)").run(Date.now());
 db.prepare("INSERT INTO worker_slots(worker_id) VALUES('venus')").run();
 db.prepare("INSERT INTO workspaces VALUES('venus','primary',1,'/tmp','github.com/acme/repo',1)").run();
 db.prepare("INSERT INTO sessions(session_id,kind,worker_id,workspace_id,workspace_version,repo_id,path) VALUES('s','worker','venus','primary',1,'github.com/acme/repo','/tmp')").run();
 db.prepare("INSERT INTO jobs(job_id,session_id,client_request_id,request_hash,input_text,worker_id,queue_seq,state,created_at) VALUES('j','s','r','h','run','venus',1,'running',?)").run(Date.now());
 db.prepare("INSERT INTO runtime_turns VALUES('j','turn','{}','h',?)").run(Date.now());
 const args={path:"README.md",offset:0,limit:20},callId="c";
 const req={worker_id:"venus",job_id:"j",call_id:callId,call_seq:1,workspace_id:"primary",config_version:1,tool:"read",arguments:args};
 const digest=requestHash(req);
 db.prepare("INSERT INTO runtime_calls(job_id,turn_key,call_id,call_seq,request_hash,tool_name,arguments_json,status) VALUES('j','turn','c',1,?,'read',?,'committed')").run(digest,JSON.stringify(args));
 const sent:string[]=[];const socket={readyState:1,send:(v:string)=>sent.push(v)};
 const conn=new Map([["venus",{epoch:2,socket,tokenDigest:"token"}]]);
 const coordinator=new ExecutionCoordinator(db,conn);
 const dispatched=coordinator.dispatch("venus","j",{workspace_id:"primary",workspace_version:1},"read",args,callId);
 const tool=JSON.parse(sent[0]);assert.equal(tool.type,"tool_call");assert.equal(tool.request_hash,digest);assert.equal(tool.call_id,callId);
 coordinator.receive({protocol_version:1,type:"tool_result",worker_id:"venus",connection_epoch:2,job_id:"j",call_id:callId,request_hash:digest,ok:true,result:{text:"fixture"}});
 assert.deepEqual(await dispatched,{text:"fixture"});assert.equal(JSON.parse(sent[1]).type,"tool_ack");
 assert.equal((db.prepare("SELECT state FROM tool_calls WHERE call_id='c'").get() as any).state,"finished");
 assert.equal((db.prepare("SELECT status FROM runtime_calls WHERE call_id='c'").get() as any).status,"completed");
 assert.equal(((db.prepare("SELECT count(*) n FROM messages WHERE job_id='j'").get() as any).n),1);
 const content="worker-plane-large-write/".repeat(5000),writeArgs={path:"large.txt",content,expected_hash:"missing"};
 const writeReq={worker_id:"venus",job_id:"j",call_id:"w",call_seq:2,workspace_id:"primary",config_version:1,tool:"write",arguments:writeArgs},writeHash=requestHash(writeReq);
 db.prepare("INSERT INTO runtime_turns VALUES('j','turn-write','{}','h',?)").run(Date.now());
 db.prepare("INSERT INTO runtime_calls(job_id,turn_key,call_id,call_seq,request_hash,tool_name,arguments_json,status) VALUES('j','turn-write','w',2,?,'write',?,'committed')").run(writeHash,JSON.stringify(writeArgs));
 const large=coordinator.dispatch("venus","j",{workspace_id:"primary",workspace_version:1},"write",writeArgs,"w");
 const frames=sent.slice(2).map((x:string)=>JSON.parse(x));assert.equal(frames[0].type,"tool_call");assert.equal(frames[0].arguments.transfer_bytes,Buffer.byteLength(content));
 const payload=Buffer.concat(frames.slice(1).map((f:any)=>Buffer.from(f.data,"base64"))).toString("utf8");assert.equal(payload,content);assert.ok(sent.slice(2).every((x:string)=>Buffer.byteLength(x)<=MAX_FRAME_BYTES));assert.equal(frames.at(-1).final,true);
 coordinator.receive({protocol_version:1,type:"tool_result",worker_id:"venus",connection_epoch:2,job_id:"j",call_id:"w",request_hash:writeHash,ok:true,result:{bytes:content.length}});
 assert.deepEqual(await large,{bytes:content.length});
 db.close();
});
